import csv
import os


# ---------------------------------------------------------
# PROJECT PATHS
# ---------------------------------------------------------

PROJECT_ROOT = os.path.dirname(
    os.path.dirname(
        os.path.abspath(__file__)
    )
)

RESULTS_DIR = os.path.join(
    PROJECT_ROOT,
    "experiments",
    "results"
)

INPUT_CSV = os.path.join(
    RESULTS_DIR,
    "genai_stress_results.csv"
)

STRESS_OUTPUT_CSV = os.path.join(
    RESULTS_DIR,
    "final_stress_results.csv"
)

OVERALL_OUTPUT_CSV = os.path.join(
    RESULTS_DIR,
    "final_overall_comparison.csv"
)


# ---------------------------------------------------------
# SCHEDULER ORDER
# ---------------------------------------------------------

SCHEDULERS = [
    "Round Robin",
    "Resource Only",
    "GenAI + Dynamic QoS"
]


# ---------------------------------------------------------
# LOAD ACTUAL EXPERIMENT RESULTS
# ---------------------------------------------------------

def load_results():
    """
    Load the actual results generated by
    services.genai_stress_evaluation.
    """

    if not os.path.exists(INPUT_CSV):
        raise FileNotFoundError(
            f"Actual experiment results not found:\n"
            f"{INPUT_CSV}\n\n"
            f"Run this first:\n"
            f"python -m services.genai_stress_evaluation"
        )

    results = []

    with open(
        INPUT_CSV,
        "r",
        newline="",
        encoding="utf-8"
    ) as file:

        reader = csv.DictReader(file)

        required_fields = [
            "scenario",
            "scheduler",
            "total_tasks",
            "completed_tasks",
            "failed_tasks",
            "deadline_success_rate",
            "average_execution_time",
            "average_qos"
        ]

        missing_fields = [
            field
            for field in required_fields
            if field not in reader.fieldnames
        ]

        if missing_fields:
            raise ValueError(
                "Input CSV is missing required fields: "
                + ", ".join(missing_fields)
            )

        for row in reader:

            results.append({
                "scenario": row["scenario"],
                "scheduler": row["scheduler"],
                "total_tasks": int(row["total_tasks"]),
                "completed_tasks": int(row["completed_tasks"]),
                "failed_tasks": int(row["failed_tasks"]),
                "deadline_success_rate": float(
                    row["deadline_success_rate"]
                ),
                "average_execution_time": float(
                    row["average_execution_time"]
                ),
                "average_qos": float(
                    row["average_qos"]
                )
            })

    if len(results) != 18:
        raise ValueError(
            f"Expected 18 results "
            f"(6 scenarios × 3 schedulers), "
            f"but found {len(results)}."
        )

    return results


# ---------------------------------------------------------
# VALIDATE RESULTS
# ---------------------------------------------------------

def validate_results(results):

    scenarios = sorted(
        set(
            row["scenario"]
            for row in results
        )
    )

    if len(scenarios) != 6:
        raise ValueError(
            f"Expected 6 scenarios, "
            f"but found {len(scenarios)}: {scenarios}"
        )

    for scenario in scenarios:

        scenario_rows = [
            row
            for row in results
            if row["scenario"] == scenario
        ]

        if len(scenario_rows) != 3:
            raise ValueError(
                f"Scenario '{scenario}' does not contain "
                f"exactly 3 scheduler results."
            )

        scenario_schedulers = {
            row["scheduler"]
            for row in scenario_rows
        }

        if scenario_schedulers != set(SCHEDULERS):
            raise ValueError(
                f"Scenario '{scenario}' has unexpected "
                f"schedulers: {scenario_schedulers}"
            )


# ---------------------------------------------------------
# SAVE FINAL STRESS RESULTS
# ---------------------------------------------------------

def save_final_stress_results(results):

    fieldnames = [
        "scenario",
        "scheduler",
        "total_tasks",
        "completed_tasks",
        "failed_tasks",
        "deadline_success_rate",
        "average_execution_time",
        "average_qos"
    ]

    with open(
        STRESS_OUTPUT_CSV,
        "w",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames
        )

        writer.writeheader()

        for row in results:

            writer.writerow({
                "scenario": row["scenario"],
                "scheduler": row["scheduler"],
                "total_tasks": row["total_tasks"],
                "completed_tasks": row["completed_tasks"],
                "failed_tasks": row["failed_tasks"],
                "deadline_success_rate": round(
                    row["deadline_success_rate"],
                    2
                ),
                "average_execution_time": round(
                    row["average_execution_time"],
                    2
                ),
                "average_qos": round(
                    row["average_qos"],
                    2
                )
            })

    print(
        f"Final stress results saved: "
        f"{STRESS_OUTPUT_CSV}"
    )


# ---------------------------------------------------------
# CALCULATE OVERALL RESULTS
# ---------------------------------------------------------

def calculate_overall_results(results):

    overall = {}

    for scheduler in SCHEDULERS:

        rows = [
            row
            for row in results
            if row["scheduler"] == scheduler
        ]

        if not rows:
            raise ValueError(
                f"No results found for scheduler: {scheduler}"
            )

        total_tasks = sum(
            row["total_tasks"]
            for row in rows
        )

        completed_tasks = sum(
            row["completed_tasks"]
            for row in rows
        )

        failed_tasks = sum(
            row["failed_tasks"]
            for row in rows
        )

        # Each scenario contains 10 tasks, so averaging the
        # six scenario-level rates is equivalent to task-weighted
        # averaging for this experiment.
        deadline_success_rate = (
            sum(
                row["deadline_success_rate"]
                for row in rows
            )
            / len(rows)
        )

        average_execution_time = (
            sum(
                row["average_execution_time"]
                for row in rows
            )
            / len(rows)
        )

        average_qos = (
            sum(
                row["average_qos"]
                for row in rows
            )
            / len(rows)
        )

        overall[scheduler] = {
            "scheduler": scheduler,
            "total_tasks": total_tasks,
            "completed_tasks": completed_tasks,
            "failed_tasks": failed_tasks,
            "deadline_success_rate": round(
                deadline_success_rate,
                2
            ),
            "average_execution_time": round(
                average_execution_time,
                2
            ),
            "average_qos": round(
                average_qos,
                2
            )
        }

    return overall


# ---------------------------------------------------------
# SAVE OVERALL COMPARISON
# ---------------------------------------------------------

def save_overall_results(overall):

    fieldnames = [
        "scheduler",
        "total_tasks",
        "completed_tasks",
        "failed_tasks",
        "deadline_success_rate",
        "average_execution_time",
        "average_qos"
    ]

    with open(
        OVERALL_OUTPUT_CSV,
        "w",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames
        )

        writer.writeheader()

        for scheduler in SCHEDULERS:

            writer.writerow(
                overall[scheduler]
            )

    print(
        f"Overall comparison saved: "
        f"{OVERALL_OUTPUT_CSV}"
    )


# ---------------------------------------------------------
# CALCULATE IMPROVEMENTS
# ---------------------------------------------------------

def calculate_improvements(overall):

    rr = overall["Round Robin"]

    resource = overall["Resource Only"]

    genai = overall["GenAI + Dynamic QoS"]

    execution_improvement_rr = (
        (
            rr["average_execution_time"]
            - genai["average_execution_time"]
        )
        / rr["average_execution_time"]
    ) * 100

    execution_improvement_resource = (
        (
            resource["average_execution_time"]
            - genai["average_execution_time"]
        )
        / resource["average_execution_time"]
    ) * 100

    qos_improvement_rr = (
        (
            genai["average_qos"]
            - rr["average_qos"]
        )
        / rr["average_qos"]
    ) * 100

    qos_improvement_resource = (
        (
            genai["average_qos"]
            - resource["average_qos"]
        )
        / resource["average_qos"]
    ) * 100

    return {
        "execution_improvement_rr":
            execution_improvement_rr,

        "execution_improvement_resource":
            execution_improvement_resource,

        "qos_improvement_rr":
            qos_improvement_rr,

        "qos_improvement_resource":
            qos_improvement_resource
    }


# ---------------------------------------------------------
# DISPLAY FINAL RESULTS
# ---------------------------------------------------------

