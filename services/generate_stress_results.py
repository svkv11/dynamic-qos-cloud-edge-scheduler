def create_summary_graph(
    results
):
    scenarios = get_scenarios(
        results
    )

    schedulers = [
        "Round Robin",
        "Resource Only",
        "GenAI + Dynamic QoS"
    ]

    x_positions = range(
        len(scenarios)
    )

    width = 0.25

    for offset, scheduler in zip(
        [-width, 0, width],
        schedulers
    ):

        values = [
            get_scheduler_value(
                results,
                scenario,
                scheduler,
                "average_qos"
            )
            for scenario in scenarios
        ]

        positions = [
            x + offset
            for x in x_positions
        ]

        plt.bar(
            positions,
            values,
            width=width,
            label=scheduler
        )

    plt.title(
        "QoS Comparison Across Stress Scenarios"
    )

    plt.xlabel(
        "Stress Scenario"
    )

    plt.ylabel(
        "Average QoS Score"
    )

    plt.xticks(
        list(x_positions),
        scenarios,
        rotation=25,
        ha="right"
    )

    plt.legend()
    plt.tight_layout()

    plt.savefig(
        SUMMARY_GRAPH,
        dpi=300
    )

    plt.close()

    print(
        f"Graph created: {SUMMARY_GRAPH}"
    )


