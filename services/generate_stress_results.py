import csv
import os

import matplotlib.pyplot as plt


PROJECT_ROOT = os.path.dirname(
    os.path.dirname(
        os.path.abspath(__file__)
    )
)

RESULTS_DIR = os.path.join(
    PROJECT_ROOT,
    "experiments",
    "results"
)

CSV_FILE = os.path.join(
    RESULTS_DIR,
    "genai_stress_results.csv"
)

EXECUTION_GRAPH = os.path.join(
    RESULTS_DIR,
    "execution_time_comparison.png"
)

QOS_GRAPH = os.path.join(
    RESULTS_DIR,
    "qos_comparison.png"
)

DEADLINE_GRAPH = os.path.join(
    RESULTS_DIR,
    "deadline_success_comparison.png"
)

SUMMARY_GRAPH = os.path.join(
    RESULTS_DIR,
    "scheduler_comparison.png"
)


def load_results():
    """
    Load the actual results generated by
    genai_stress_evaluation.py.
    """

    if not os.path.exists(CSV_FILE):
        raise FileNotFoundError(
            f"Results CSV not found: {CSV_FILE}\n"
            "Run the stress evaluation first."
        )

    results = []

    with open(
        CSV_FILE,
        "r",
        newline="",
        encoding="utf-8"
    ) as file:

        reader = csv.DictReader(file)

        for row in reader:

            results.append({
                "scenario": row["scenario"],
                "scheduler": row["scheduler"],
                "total_tasks": int(
                    row["total_tasks"]
                ),
                "completed_tasks": int(
                    row["completed_tasks"]
                ),
                "failed_tasks": int(
                    row["failed_tasks"]
                ),
                "deadline_success_rate": float(
                    row["deadline_success_rate"]
                ),
                "average_execution_time": float(
                    row["average_execution_time"]
                ),
                "average_qos": float(
                    row["average_qos"]
                )
            })

    if len(results) != 18:
        raise ValueError(
            "Expected 18 result rows "
            "(6 scenarios × 3 schedulers), "
            f"but found {len(results)}."
        )

    return results


def get_scenarios(results):
    """
    Return scenarios in the order in which they
    appear in the experiment results.
    """

    return list(
        dict.fromkeys(
            result["scenario"]
            for result in results
        )
    )


def get_scheduler_value(
    results,
    scenario,
    scheduler,
    metric
):
    """
    Get one metric value for a scenario and scheduler.
    """

    matching = [
        result
        for result in results
        if (
            result["scenario"] == scenario
            and result["scheduler"] == scheduler
        )
    ]

    if len(matching) != 1:
        raise ValueError(
            f"Expected exactly one result for "
            f"{scenario} / {scheduler}, "
            f"found {len(matching)}."
        )

    return matching[0][metric]


def create_execution_time_graph(
    results
):
    scenarios = get_scenarios(
        results
    )

    schedulers = [
        "Round Robin",
        "Resource Only",
        "GenAI + Dynamic QoS"
    ]

    for scheduler in schedulers:

        values = [
            get_scheduler_value(
                results,
                scenario,
                scheduler,
                "average_execution_time"
            )
            for scenario in scenarios
        ]

        plt.plot(
            scenarios,
            values,
            marker="o",
            label=scheduler
        )

    plt.title(
        "Average Execution Time Comparison"
    )

    plt.xlabel(
        "Stress Scenario"
    )

    plt.ylabel(
        "Average Execution Time (seconds)"
    )

    plt.xticks(
        rotation=25,
        ha="right"
    )

    plt.legend()
    plt.tight_layout()

    plt.savefig(
        EXECUTION_GRAPH,
        dpi=300
    )

    plt.close()

    print(
        f"Graph created: {EXECUTION_GRAPH}"
    )


